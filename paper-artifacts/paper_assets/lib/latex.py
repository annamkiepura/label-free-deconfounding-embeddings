PREAMBLE = r"""\documentclass[11pt,a4paper]{article}
\usepackage{times,latexsym}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage[]{tacl2021v1}
\usepackage{amsmath,amssymb,booktabs,graphicx,microtype}
\begin{document}
"""


#: The TACL page without its style file: 11pt article, Times, the geometry the style sets (text
#: block and column width from `config`) and \small captions. Calibrated on the committed Table B2,
#: which the real style typeset on one page: on this page its float also fits and its measured
#: height is the same (697.0pt). Used only when tacl2021v1.sty is not available.
STANDIN_PREAMBLE = (r"""\documentclass[11pt,a4paper,twocolumn]{article}
\usepackage{times,latexsym}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage[a4paper,textwidth=""" + f"{config.TEXT_WIDTH_IN * 72.27:.5f}pt,textheight={config.TEXT_HEIGHT_PT}pt,"
                    + f"columnsep={(config.TEXT_WIDTH_IN - 2 * config.COLUMN_WIDTH_IN) * 72.27:.5f}pt" + r"""]{geometry}
\usepackage{amsmath,amssymb,booktabs,graphicx,microtype}
\usepackage[font=small]{caption}
\begin{document}
""")


def _page(tmp: Path) -> str:
    """The preamble to compile against: the manuscript's own style if present (copied into `tmp`),
    else the stand-in page, with a warning."""
    from .provenance import issue
    style = config.REPO / config.manifest()["tacl_style_dir"] / "tacl2021v1.sty"
    if style.exists():
        shutil.copy(style, tmp)
        return PREAMBLE
    issue("warning", "tacl_style_standin", f"{style.relative_to(config.REPO)} not found: measured on a stand-in "
          f"page with the TACL geometry ({config.TEXT_WIDTH_IN * 72.27:.2f}pt x {config.TEXT_HEIGHT_PT}pt text, "
          f"{config.COLUMN_WIDTH_IN * 72.27:.2f}pt columns, Times)")
    return STANDIN_PREAMBLE


def have_latex() -> bool:
    return shutil.which("pdflatex") is not None


def _exhibit_labels() -> dict:
    """label -> number shown in a standalone preview, from each exhibit's NAME
    (``table2_*`` -> 2, ``fig3_*`` -> 3, ``tableB1_*`` -> B1), plus the labels an exhibit's
    companion text for the manuscript defines (its TEXT_LABELS, shown as declared)."""
    import importlib
    from ..exhibits import ORDER
    out = {}
    for n in ORDER:
        mod = importlib.import_module(f"..exhibits.{n}", __package__)
        m = re.match(r"(?:table|tab|fig)([A-Z]?\d+)_", n)
        if getattr(mod, "LABEL", None) and m:
            out.setdefault(mod.LABEL, m.group(1))
        for label, shown in getattr(mod, "TEXT_LABELS", {}).items():
            out.setdefault(label, shown)
    return out


def _ref_stubs(name: str, tex: str) -> str:
    """Define references to OTHER exhibits' labels, so a standalone preview shows
    their manuscript number; unknown labels stay undefined and fail the check."""
    from .provenance import check
    refs = set(re.findall(r"\\ref\{([^}]+)\}", tex)) - set(re.findall(r"\\label\{([^}]+)\}", tex))
    known = _exhibit_labels()
    stubs = {r: known[r] for r in sorted(refs) if r in known}
    for r, n in stubs.items():
        check(True, "latex_ref_other_exhibit", f"{name}: \\ref{{{r}}} points to another exhibit or its text "
              f"(shown as {n} in the preview; the manuscript resolves it)")
    if not stubs:
        return ""
    return ("\\makeatletter\n" + "".join(f"\\@namedef{{r@{r}}}{{{{{n}}}{{}}}}\n" for r, n in stubs.items())
            + "\\makeatother\n")


def measure(body: str) -> dict:
    """Compile ``body`` on a TACL page and return every ``\\typeout{MEASURE key=value}``."""
    if not have_latex():
        return {}
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        (tmp / "m.tex").write_text(_page(tmp) + body + "\n\\end{document}\n")
        subprocess.run(["pdflatex", "-interaction=nonstopmode", "m.tex"], cwd=tmp, capture_output=True, text=True)
        log = (tmp / "m.log").read_text(errors="replace") if (tmp / "m.log").exists() else ""
    return dict(re.findall(r"MEASURE (\S+)=(\S+)", log))


def compile_preview(name: str, float_tex: str, ex) -> Path | None:
    """Compile one exhibit on a TACL page; write reports/previews/<name>.{pdf,png}.

    Records overfull boxes (wider than the column/text) as errors."""
    from .provenance import check, issue
    if not have_latex():
        issue("warning", "no_latex", f"{name}: pdflatex not available; preview not compiled")
        return None
    outdir = config.OUT_DIRS["reports"] / "previews"
    outdir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        preamble = _page(tmp)
        (tmp / "paper_assets").symlink_to(config.PKG)
        (tmp / config.HOME.name).symlink_to(config.HOME)            # include files point at paper-artifacts/
        cites = "\\cite" in float_tex
        tail = "\n\\clearpage\n"
        m = config.manifest()
        if cites and not (config.REPO / m["bibliography"]).exists():
            # The manuscript's bibliography is not part of the repository: show citation keys instead.
            issue("warning", "no_bibliography", f"{name}: {m['bibliography']} not found; the preview shows "
                  "citation keys")
            float_tex = ("\\providecommand{\\citet}[1]{\\texttt{#1}}\\providecommand{\\citep}[1]{(\\texttt{#1})}"
                         "\\renewcommand{\\cite}[1]{\\texttt{#1}}\n" + float_tex)
            cites = False
        if cites:        # resolve citations against the manuscript's own bibliography
            shutil.copy(config.REPO / m["bibliography"], tmp / "references.bib")
            shutil.copy(config.REPO / m["bibliography_style"], tmp / "acl_natbib.bst")
            tail += "\\bibliographystyle{acl_natbib}\n\\bibliography{references}\n"
        doc = preamble + _ref_stubs(name, float_tex) + float_tex + tail + "\\end{document}\n"
        (tmp / "preview.tex").write_text(doc)
        steps = [["pdflatex", "-interaction=nonstopmode", "-halt-on-error", "preview.tex"]]
        if cites:
            steps += [["bibtex", "preview"]] + steps * 2
        elif "\\ref" in float_tex:          # a reference inside the float(s) needs a second pass
            steps = steps * 2
        for cmd in steps:
            r = subprocess.run(cmd, cwd=tmp, capture_output=True, text=True)
            if r.returncode != 0 and cmd[0] == "pdflatex":
                break
        log = (tmp / "preview.log").read_text(errors="replace") if (tmp / "preview.log").exists() else r.stdout
        if r.returncode != 0:
            issue("error", "latex_failed", f"{name}: preview failed to compile",
                  log_tail=log[-2000:])
            return None
        undefined = [l for l in log.splitlines() if "undefined" in l and ("Citation" in l or "Reference" in l)]
        check(not undefined, "latex_citations_resolved", f"{name}: every citation and reference resolves",
              undefined=undefined)
        too_large = [l for l in log.splitlines() if "Float too large" in l]
        check(not too_large, "latex_float_fits", f"{name}: the float fits the TACL text block", too_large=too_large)
        overfull = [l for l in log.splitlines() if l.startswith("Overfull \\hbox")]
        check(not overfull, "latex_no_overfull", f"{name}: no overfull boxes in the TACL preview",
              overfull=overfull)
        pdf = outdir / f"{name}.pdf"
        shutil.copy(tmp / "preview.pdf", pdf)
    png = outdir / f"{name}.png"
    if shutil.which("gs"):
        subprocess.run(["gs", "-q", "-dSAFER", "-dBATCH", "-dNOPAUSE", "-sDEVICE=png16m", "-r150",
                        "-dFirstPage=1", "-dLastPage=1", f"-sOutputFile={png}", str(pdf)],
                       capture_output=True)
    ex.output(pdf)
    if png.exists():
        ex.output(png)
    return pdf
