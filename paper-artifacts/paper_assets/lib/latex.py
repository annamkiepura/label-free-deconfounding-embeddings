DIGITS = config.manifest()["conventions"]["display_digits"]
MISSING_TEX = r"\textsc{nr}"          # not recorded: listed in the validation report
NA_TEX = "--"
PENDING_TEX = r"\textit{Pending}"


def num(x: float, digits: int = DIGITS, signed: bool = False, lead_zero: bool = False) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return MISSING_TEX
    if round(x, digits) == 0:
        x = 0.0                      # a value that rounds to zero is shown unsigned
        signed = False
    s = f"{x:+.{digits}f}" if signed else f"{x:.{digits}f}"
    if not lead_zero:
        s = s.replace("0.", ".", 1) if abs(x) < 1 else s
    return s.replace("-", "$-$") if signed or x < 0 else s


def cell(sv: SeedValues, sd: bool = True, signed: bool = False, digits: int = DIGITS,
         bold: bool = False) -> str:
    """One table cell from seed values: mean with the SD as a small subscript."""
    if sv.status == PENDING:
        return PENDING_TEX
    if sv.status == NOT_APPLICABLE:
        return NA_TEX
    if sv.status != OK:
        return MISSING_TEX
    m = num(sv.mean, digits, signed)
    if bold:
        m = rf"\textbf{{{m}}}"
    if sd and sv.n > 1:
        return rf"{m}{{\scriptsize$\,\pm${num(sv.sd, digits)}}}"
    return m


def esc(s: str) -> str:
    return (s.replace("&", r"\&").replace("%", r"\%").replace("#", r"\#")
            if "$" not in s and "\\" not in s else s)


def tabular(colspec: str, header: list[list[str]], body: list, *, midrules=(),
            cmidrules: list[str] | None = None) -> list[str]:
    """booktabs tabular. `header` is a list of header rows; `body` rows are
    lists of cell strings, or the string "\\midrule" / "\\addlinespace"."""
    out = [rf"\begin{{tabular}}{{{colspec}}}", r"\toprule"]
    for i, row in enumerate(header):
        out.append(" & ".join(row) + r" \\")
        if cmidrules and i < len(cmidrules) and cmidrules[i]:
            out.append(cmidrules[i])
    out.append(r"\midrule")
    for i, row in enumerate(body):
        if isinstance(row, str):
            out.append(row)
            continue
        if i in midrules:
            out.append(r"\midrule")
        out.append(" & ".join(row) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    return out


def write_table(name: str, lines: list[str], caption: str, label: str, ex, *, wide: bool,
                size: str = r"\small", tabcolsep: str | None = None, notes: str = "") -> Path:
    """Write tables/<name>.tex (the float, \\input-able) and tables/<name>.include.tex."""
    env = "table*" if wide else "table"
    body = ["% Generated by paper_assets; do not edit by hand. Rebuild:",
            f"%   python -m paper_assets build {name}",
            f"% Data and provenance: paper_assets/data/{name}.csv, {name}.provenance.json",
            rf"\begin{{{env}}}[t]", r"\centering", size]
    if tabcolsep:
        body.append(rf"\setlength{{\tabcolsep}}{{{tabcolsep}}}")
    body += lines
    if notes:
        body.append(rf"\par\smallskip\parbox{{\linewidth}}{{\footnotesize {notes}}}")
    body += [rf"\caption{{{caption}}}", rf"\label{{{label}}}", rf"\end{{{env}}}", ""]
    p = config.OUT_DIRS["tables"] / f"{name}.tex"
    p.write_text("\n".join(body))
    ex.output(p)
    inc = config.OUT_DIRS["tables"] / f"{name}.include.tex"
    inc.write_text(f"% Include in the manuscript (requires booktabs):\n"
                   f"\\input{{paper_assets/tables/{name}}}\n% Cross-reference: Table~\\ref{{{label}}}\n")
    ex.output(inc)
    ex.caption = caption
    return p


def write_figure_include(name: str, caption: str, label: str, ex, *, wide: bool) -> Path:
    env = "figure*" if wide else "figure"
    width = r"\textwidth" if wide else r"\columnwidth"
    text = [f"% Generated by paper_assets. Rebuild: python -m paper_assets build {name}",
            f"% Figure drawn at the exact {width}; include without rescaling.",
            rf"\begin{{{env}}}[t]", r"\centering",
            rf"\includegraphics[width={width}]{{paper_assets/figures/{name}.pdf}}",
            rf"\caption{{{caption}}}", rf"\label{{{label}}}", rf"\end{{{env}}}", ""]
    p = config.OUT_DIRS["figures"] / f"{name}.include.tex"
    p.write_text("\n".join(text))
    ex.output(p)
    ex.caption = caption
    return p


def write_csv(name: str, rows: list[dict], ex) -> Path:
    """The plotted/tabulated data: one row per displayed value, unrounded."""
    p = config.OUT_DIRS["data"] / f"{name}.csv"
    keys: list[str] = []
    for r in rows:
        for k in r:
            if k not in keys:
                keys.append(k)
    with p.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        for r in rows:
            w.writerow({k: ("|".join(map(str, v)) if isinstance(v, (list, tuple)) else v)
                        for k, v in r.items()})
    ex.output(p)
    return p


def sv_row(sv: SeedValues, **extra) -> dict:
    return {**extra, "setting": sv.setting, "encoder": sv.encoder, "method": sv.method,
            "metric": sv.metric, "status": sv.status, "cohort": sv.cohort, "n_seeds": sv.n,
            "seeds": sv.seeds, "mean": sv.mean if sv.ok else "", "sd": sv.sd if sv.ok else "",
            "sd_ddof": config.manifest()["conventions"]["sd_ddof"], "values": sv.values,
            "source_files": [s["file"] for s in sv.sources],
            "run_ids": [s["run_id"] for s in sv.sources],
            "conditions": [s["condition"] for s in sv.sources], "reason": sv.reason}


